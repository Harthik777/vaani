"""Server-side exports of the compiled BRD: PDF, Excel traceability matrix, and the pack by email."""
import re
from fastapi import APIRouter, HTTPException
from fastapi.responses import Response
from pydantic import BaseModel, Field
from models import CompileIn
from services import mailer
from services.compiler import document

router = APIRouter()


def file_stem(brd: dict) -> str:
    return (re.sub(r"[^A-Za-z0-9]+", "-", brd.get("project_name") or "brd").strip("-") or "brd")[:60]


@router.post("/api/brd/pdf")
async def pdf(body: CompileIn):
    from services.pdf import build_pdf
    brd = document(body)
    try:
        data = build_pdf(brd, body.translations)
    except Exception as exc:
        raise HTTPException(500, f"PDF generation failed: {exc}") from exc
    return Response(data, media_type="application/pdf", headers={"Content-Disposition": f'attachment; filename="{file_stem(brd)}.pdf"'})


@router.post("/api/brd/xlsx")
async def xlsx(body: CompileIn):
    from services.xlsx import build_xlsx
    brd = document(body)
    data = build_xlsx(brd, body.translations)
    return Response(data, media_type="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
                    headers={"Content-Disposition": f'attachment; filename="{file_stem(brd)}-traceability.xlsx"'})


class EmailIn(CompileIn):
    to: list[str] = Field(min_length=1, max_length=5)
    note: str = Field(default="", max_length=2000)


@router.post("/api/brd/email")
async def email(body: EmailIn):
    if not mailer.enabled():
        raise HTTPException(503, "Email is not configured. Add SMTP_HOST, SMTP_USER and SMTP_PASS to backend/.env (Gmail: an app password).")
    bad = [t for t in body.to if not re.fullmatch(r"[^@\s]+@[^@\s]+\.[^@\s]+", t.strip())]
    if bad:
        raise HTTPException(422, f"Not an email address: {', '.join(bad)}")
    from services.export import build_docx
    from services.pdf import build_pdf
    from services.xlsx import build_xlsx
    brd = document(body)
    stem = file_stem(brd)
    attachments = [(f"{stem}.docx", build_docx(brd, body.translations), "application/vnd.openxmlformats-officedocument.wordprocessingml.document"),
                   (f"{stem}-traceability.xlsx", build_xlsx(brd, body.translations), "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet")]
    try:
        attachments.insert(0, (f"{stem}.pdf", build_pdf(brd, body.translations), "application/pdf"))
    except Exception:
        pass
    n = len(brd.get("business_rules") or [])
    text = (f"{brd.get('project_name')}\n\n{n} approved requirements, each quoting the speaker exactly. "
            f"{len(brd.get('open_questions') or [])} open questions.\n\n{body.note.strip()}\n\nGenerated by VAANI.").strip()
    try:
        result = mailer.send([t.strip() for t in body.to], f"BRD: {brd.get('project_name')}", text, attachments)
    except Exception as exc:
        raise HTTPException(502, f"Email failed: {exc}") from exc
    return result
